# When using a dictionary in Python, there are a few rules about keys - a key
# can be a number, a string, a Boolean or tuple.  Each key should be unique, but if 
# there are duplicates, the last key in the list is the one used.  Each key receives
# a value, and the values do not ahve to be unique.  Keys must be immutable, which 
# means the key must be a data type hat cannon thange after it was created.

# Dictionaires are orderes - they remain in the order they were created.  If you change
# the value of a key-value pair, the order of the dictionary remains the same.  If the
# key-value pair was deleted from the dictionary completely and then re-added, the new 
# position of the key-value pair woudl be at the end of the list.  If a list needs to be
# sortedin a different way, there are some tools, such as using the sorted() function
